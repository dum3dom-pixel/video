"""Generate per-scene narration (edge-tts) for an explainer spec and write durations.

Usage (from my-video/):
    python scripts/explainer_tts.py src/Explainer/videos/<id>.json [--force] [--rate=+0%]

Writes:
    public/explainer/<id>/voice/<sceneId>.mp3
    public/explainer/<id>/voice/<id>.voice.hash.json   (text/voice hash cache)
    public/explainer/<id>/voice/<id>.voice.words.json  (word timings cache, seconds)
    src/Explainer/videos/<id>.voice.ts                 (voiceDurations + voiceWords, seconds)
"""
import argparse
import asyncio
import hashlib
import json
import subprocess
import sys
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_VOICE = "ru-RU-DmitryNeural"
FFPROBE = ROOT / "node_modules" / "@remotion" / "compositor-win32-x64-msvc" / "ffprobe.exe"


def probe_duration(path: Path) -> float:
    """Exact duration in seconds via Remotion's bundled ffprobe."""
    out = subprocess.run(
        [str(FFPROBE), "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return float(out)


def text_hash(text: str, voice: str, rate: str) -> str:
    return hashlib.sha1(f"{voice}|{rate}|{text}".encode("utf-8")).hexdigest()


async def synth(text: str, voice: str, rate: str, path: Path) -> list[dict]:
    """Write mp3, return word timings [{t, d, w}] in seconds (offset/duration come in 100ns units)."""
    try:
        communicate = edge_tts.Communicate(text, voice, rate=rate, boundary="WordBoundary")
    except TypeError:  # older edge_tts: WordBoundary is the default, no `boundary` param
        communicate = edge_tts.Communicate(text, voice, rate=rate)
    words: list[dict] = []
    with open(path, "wb") as f:
        async for chunk in communicate.stream():
            if chunk["type"] == "audio":
                f.write(chunk["data"])
            elif chunk["type"] == "WordBoundary":
                words.append({
                    "t": round(chunk["offset"] / 1e7, 3),
                    "d": round(chunk["duration"] / 1e7, 3),
                    "w": chunk["text"],
                })
    return words


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec", help="path to src/Explainer/videos/<id>.json")
    ap.add_argument("--force", action="store_true", help="regenerate all mp3s")
    ap.add_argument("--rate", default=None, help='edge-tts rate override, e.g. --rate=-5%% (default: spec "rate" or +0%%)')
    args = ap.parse_args()

    spec_path = (ROOT / args.spec) if not Path(args.spec).is_absolute() else Path(args.spec)
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    spec_id = spec["id"]
    voice = spec.get("voice") or DEFAULT_VOICE
    rate = args.rate or spec.get("rate") or "+0%"

    if not FFPROBE.exists():
        print(f"ffprobe not found: {FFPROBE}", file=sys.stderr)
        return 1

    out_dir = ROOT / "public" / "explainer" / spec_id / "voice"
    out_dir.mkdir(parents=True, exist_ok=True)
    hash_path = out_dir / f"{spec_id}.voice.hash.json"
    hashes = json.loads(hash_path.read_text(encoding="utf-8")) if hash_path.exists() else {}

    words_path = out_dir / f"{spec_id}.voice.words.json"
    all_words: dict[str, list] = json.loads(words_path.read_text(encoding="utf-8")) if words_path.exists() else {}

    durations: dict[str, float] = {}
    rows = []
    for scene in spec["scenes"]:
        text = scene.get("voice")
        if not text:
            continue
        sid = scene["id"]
        mp3 = out_dir / f"{sid}.mp3"
        h = text_hash(text, voice, rate)
        if args.force or not mp3.exists() or hashes.get(sid) != h or not all_words.get(sid):
            all_words[sid] = await synth(text, voice, rate, mp3)
            hashes[sid] = h
            status = "generated"
        else:
            status = "cached"
        durations[sid] = round(probe_duration(mp3), 3)
        rows.append((sid, status, durations[sid], text))
        if not all_words.get(sid):
            print(f"warning: no word timings for scene {sid}", file=sys.stderr)

    # drop stale hashes / durations of scenes that no longer have voice
    hashes = {k: v for k, v in hashes.items() if k in durations}
    all_words = {k: v for k, v in all_words.items() if k in durations}
    hash_path.write_text(json.dumps(hashes, indent=2), encoding="utf-8")
    words_path.write_text(json.dumps(all_words, ensure_ascii=False), encoding="utf-8")

    ts = (
        "// Generated by scripts/explainer_tts.py — do not edit.\n"
        "export const voiceDurations: Record<string, number> = "
        + json.dumps(durations, ensure_ascii=False, indent=2)
        + ";\n"
        "export const voiceWords: Record<string, {t: number; d: number; w: string}[]> = "
        + json.dumps(all_words, ensure_ascii=False, indent=2)
        + ";\n"
    )
    ts_path = spec_path.with_name(f"{spec_id}.voice.ts")
    ts_path.write_text(ts, encoding="utf-8")

    print(f"voice: {voice}   spec: {spec_id}")
    print(f"{'scene':<12}{'status':<11}{'sec':>7}  text")
    for sid, status, dur, text in rows:
        short = text if len(text) <= 48 else text[:45] + "..."
        print(f"{sid:<12}{status:<11}{dur:>7.2f}  {short}")
    total = sum(durations.values())
    print(f"voiced scenes: {len(rows)}   narration total: {total:.2f}s   -> {ts_path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(asyncio.run(main()))
