"""Текст ролика «Три года в темноте» (около минуты). 3 сплошных дубля, темп как в story_voice.py."""
import os
from f5_tts.api import F5TTS

D = r"C:\Users\daatva\voice-clone"
OUT = os.path.join(D, "out", "morganie")
os.makedirs(OUT, exist_ok=True)
v = os.path.join(D, "voices", "friend")
ref_text = open(os.path.join(v, "ref.txt"), encoding="utf-8").read().strip()
tts = F5TTS(model="F5TTS_v1_Base",
            ckpt_file=os.path.join(D, "model", "F5TTS_v1_Base_v4_winter", "model_212000.safetensors"),
            vocab_file=os.path.join(D, "model", "F5TTS_v1_Base", "vocab.txt"), device="cuda")
TEXT = ("Три с половиной года своей жизни ты проведёшь в полной темноте. И ни разу этого не заметишь. "
        "Какая темнота? Когда? Ты же вот, смотришь в экран. Это Гена. Он тоже смотрит в экран. Вот, опять. Гена моргнул. "
        "Давай посчитаем. За минуту Гена моргает примерно пятнадцать раз. Не спит он часов шестнадцать. "
        "Выходит четырнадцать тысяч четыреста морганий в день. Одно моргание длится примерно три десятых секунды. "
        "Ерунда, думает Гена. Складываем. Семьдесят две минуты в день Гена не видит вообще ничего. "
        "Как будто каждый день смотришь фильм с выключенным экраном. За семьдесят лет набегает три с половиной года. Тысяча двести с лишним дней без единого кадра. "
        "Тогда почему этой темноты никто не видел? Потому что мозг на время моргания приглушает зрение. И склеивает картинку. "
        "Как монтажёр, который вырезает лишний кадр. Гена об этом не просил. "
        "Если он вырезает темноту... что ещё он вырезал, пока ты это слушал?")
for s in (1, 2, 3):
    tts.infer(os.path.join(v, "ref.wav"), ref_text, TEXT, file_wave=os.path.join(OUT, f"full_s{s}.wav"),
              speed=0.75, seed=s, nfe_step=64, show_info=lambda *_: None)
print("done")
