"""A/B ударений для «Принципа Питера»: «+» перед ударной гласной в тексте; вариант b — плюс разметка в образце голоса."""
import os
from f5_tts.api import F5TTS

D = r"C:\Users\daatva\voice-clone"
OUT = os.path.join(D, "out", "piter")
v = os.path.join(D, "voices", "friend")
ref_plain = open(os.path.join(v, "ref.txt"), encoding="utf-8").read().strip()
ref_marked = ("Но наш гер+ой не загруст+ил, +ибо мудак+и груст+ить не ум+еют. Вм+есто +этого он объяв+ил себ+я "
              "пострад+авшим борц+ом за своб+оду сл+ова и покл+ялся до посл+едней к+апли кр+ови отст+аивать пр+ава "
              "хомячк+ов, в см+ысле пользов+ателей интерн+ета.")
# Односложные слова и слова с «ё» не размечаются.
TEXT = ("Твой нач+альник не род+ился иди+отом. Ег+о до +этого пов+ысили. "
        "Пр+инцип П+итера, шестьдес+ят дев+ятый год. "
        "Вот л+учший мех+аник в автос+ервисе. Ч+инит всё. Ег+о д+елают нач+альником. "
        "И теп+ерь он л+езет в к+аждый мот+ор, сл+есари к+урят, маш+ины сто+ят. "
        "В+ыше ег+о уж+е не подн+имут. Так и сид+ит. "
        "Мех+аника потер+яли, иди+ота получ+или. И так на к+аждом этаж+е. "
        "В две т+ысячи дес+ятом итальянцы посчит+али: повыш+ать науг+ад в+ыгоднее, чем повыш+ать л+учших. "
        "За +это им д+али Шн+обелевку. "
        "Теб+я не повыш+ают? Р+адуйся. Ты ещё не дор+ос до своег+о иди+ота.").replace("итальянцы", "итал+ьянцы")
tts = F5TTS(model="F5TTS_v1_Base",
            ckpt_file=os.path.join(D, "model", "F5TTS_v1_Base_v4_winter", "model_212000.safetensors"),
            vocab_file=os.path.join(D, "model", "F5TTS_v1_Base", "vocab.txt"), device="cuda")
for name, ref in (("stress_a", ref_plain), ("stress_b", ref_marked)):
    tts.infer(os.path.join(v, "ref.wav"), ref, TEXT, file_wave=os.path.join(OUT, f"{name}.wav"),
              speed=0.9, seed=2, nfe_step=64, show_info=lambda *_: None)
print("done")
